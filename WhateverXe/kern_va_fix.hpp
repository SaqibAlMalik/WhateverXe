// Page-in edits applied by the cs_validate patcher (kern_xe.cpp, pageIn*),
// which -wex-mtl-poshfix also uses.
//
// PageFix is the generic part: an anchor is one window of a signed binary,
// pinned to its file offset, holding the exact original bytes and their
// replacement. Anchors are at least 32 bytes and lie inside one 4 KB page, so
// a validated page either holds a whole anchor or none of it.
//
// VAFix targets the Tiger Lake VA plug-in AppleIntelTGLGraphicsVADriver
// 16.0.32 as shipped in the WhateverXe Graphics package (file sha256
// a972cdb7...726d, thin x86_64, __TEXT file offset == vmaddr). Every VAFix
// anchor occurs exactly once in that file and in no other binary of the
// package (Metal bundle, libigdmd, TGLVA, accelerator, framebuffer, Compat).
// Nothing on disk changes.
//
// -wex-va-nullguard. Apple's VphalRendererG12::AllocateRenderComponents
// (0x1b1bc0) allocates only pRender[COMPOSITE] (+0x920); pRender[VEBOX] and
// pRender[VEBOX2] (+0x910, +0x918) stay NULL for the renderer's lifetime
// (zeroed at 0x132df4/0x132dff, never assigned). The package already skips
// their Initialize calls (caves 0xd80/0xd98). Three uses remain unguarded:
//   N1 0x1336f3  status-block hookup, pRender[VEBOX]->+8 = &renderer->+0x2cb0
//                (the reported crash, VTPixelTransferSession prepare step)
//   N2 0x130e91  render preparation, SetStatusReportParams(pRender[VEBOX+ch])
//                (0x126520 writes +0x48..+0x58 of the NULL slot)
//   N3 0x12d316  VEBOX render step, virtual call on pRender[VEBOX+ch] that
//                precedes the function's own NULL check (0x12d32b -> status 5)
// A NOP at N1 alone only moves the crash to N2 on the following transfer.
// Each site instead gets an in-place test of the loaded pointer, in the same
// bytes: when it is non-NULL the same loads, store or call happen with the
// same values and the calls keep their addresses and bytes (only scratch
// registers that are dead afterwards differ); when it is NULL, N1/N2 skip only
// the store or call on that slot and N3 jumps to the function's existing NULL
// path (clear bOutputGenerated, return MOS_STATUS_NULL_POINTER). No execution
// that does not fault today behaves differently. The three anchors are
// independent. No function involved has an exception landing pad, and no
// branch lands inside a rewritten span.
//
// -wex-va-vfeg12 (hypothesis test: Gen12 MEDIA_VFE_STATE and L3 for the
// MediaKernelContext VFE builder 0x2c84a, a virtual method). Eight sites on
// two pages, one anchor per page, so a page is edited completely or not at
// all:
//   V1 0x1000   LRI helper 0x1c1b, whose only caller is the builder (0x2c8fc):
//               {reg 0x0, 0x80000040} -> {L3ALLOC 0xB134, 0xD0000020}
//   V2 0x2c000  the builder from that call to its loop exit (0x2ca67): every
//               MEDIA_VFE_STATE it emits gets DW3 bit 6 = 1 (legacy dispatch,
//               as Intel's Gen12 media driver programs it) and DW6..DW8 = 0
//               (reserved on Gen12), on both copy paths
// The builder copies the 36-byte MEDIA_VFE_STATE template 0x31d720 (DW0
// 0x70000007, DW3 0, DW6..DW8 0x000000ff 0xfff1f00f 0xefe1e01f), then
// rewrites DW3 (bits 8-15 = 0x10, bits 16-31 = threads - 1), DW5 and, by
// byte [this+0x124]:
//   path A (!= 0): DW6..DW8 zeroed by the code (0x2c9d3/0x2c9db), then a
//                  per-entry scoreboard store (dword [this+0x41cc+4i]: type 2
//                  DW6:DW7 = 0x80000001:0xf0, type 1 0x80000001:0x0f)
//   path B (== 0): DW6..DW8 kept from the template, DW6 bit 31 set
// The template itself is NOT edited: a second builder family (0x17a7f, lea
// at 0x17ad5; callers 0x188a9, 0x1912e, 0x19f98, 0x1a760, 0x1cc7b) copies it
// too, keeps DW3 bits 0-7, ORs scoreboard bits 31/30 into DW6 and has its own
// LRI helper (0x17a60), so a template edit would put that family in a state
// that is neither stock nor the hypothesis. The builder's own copy path is
// edited instead:
//   0x2c9ae, 0x2ca22  DW3 `or 0x1000` -> `or 0x1040` (paths A, B); bits 0-15
//                     survive the movzx/lea that then adds the thread count
//   0x2ca03           path B DW8 load `mov edx,[rax+0x20]` -> `xor edx,edx; nop`
//   0x2ca08           path B DW6:DW7 load `mov rdx,[rax+0x18]` ->
//                     `xor edx,edx; xchg ax,ax` (rdx = 0, flags dead)
//   0x2ca47           path B `or byte [rdi-5],0x80` (DW6 bit 31) -> 4-byte NOP
//   0x2ca4d, 0x2ca53  path A scoreboard stores `mov [rdi-8],r10/r11` -> NOPs
// Instruction boundaries and every branch target (0x2c977, 0x2c9f8, 0x2ca4d,
// 0x2ca53, 0x2ca57) are kept; the builder has no landing pad. On every path
// the emitted state equals what the earlier three-page set (template edit)
// produced for this builder, and nothing outside pages 0x1000 and 0x2c000
// changes.
// Pages are validated independently and in any order, so the set uses a
// latch (PageFix::decide/commit/poison): the first pinned hit of any member
// decides once for the boot (Armed or Off) and every later page of the set,
// including a page validated again after eviction, follows that decision.
// The builder calls the V1 helper on every batch (the call is inside the V2
// anchor), so both pages have passed validation, under the same decision,
// before a MEDIA_VFE_STATE is emitted.
// L3: V1 programs L3ALLOC 0xB134 only; Intel's Gen12 SetL3Cache also writes
// TCCNTLREG 0xB138 = 0, which V1 does not. The LRI runs from the VA driver's
// (non-privileged) batch, so it relies on the RCS FORCE_TO_NONPRIV entry
// 0x24D8 = 0xB134. The accelerator programs that list only when accel+0x1191
// bit 0 is set: IntelAccelerator::initModeRegisters 0x28EBA `test byte
// [rdi+0x1191],1; je 0x28F31` skips all of RCS 0x24D0..0x24FC and CCS
// 0x1A4D0 (-wex-tgl-gpurec restores the list under the same bit). The VFEG12
// gate does not check this bit; WEXVAFix publishes it (ready bits
// L3WhitelistSampled/L3Whitelisted, sampled when IntelAccelerator::start
// returns true while -wex-va-vfeg12 is given).
// An anchor found away from its file offset is only counted (nothing is
// written there, the latch is untouched).
// A write that fails before any member window was written poisons the set
// (no writes this boot); after the first member write the set is committed,
// a failure is counted and that page is edited at its next validation, so a
// poison can never leave an edited set split. Pages already edited cannot be
// reverted from the page-in hook.
